// Projects Natural Earth 50m land onto our chart and writes simplified SVG paths. Run: node tools/coast.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoMercator, geoPath, geoGraticule10 } from "d3-geo";
import { feature } from "topojson-client";
const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-50m.json", "utf8"));
const land = feature(topo, topo.objects.land);
const W = 1000, H = 640;
// Frame: east Africa to the Malacca strait, the Arabian peninsula to south of the equator.
const proj = geoMercator().fitExtent([[0, 0], [W, H]], { type: "MultiPoint", coordinates: [[34, 27], [106, -11]] });
const path = geoPath(proj).digits(1);
const clip = { type: "Polygon", coordinates: [[[30, 32], [30, -16], [110, -16], [110, 32], [30, 32]]] };
// Clip by intersecting via projection clipExtent instead (d3 has no polygon intersection).
proj.clipExtent([[-20, -20], [W + 20, H + 20]]);
const d = path(land);
const grat = geoPath(proj).digits(1)(geoGraticule10());
const ports = { zanzibar: [39.19, -6.16], aden: [45.03, 12.8], socotra: [53.85, 12.5], surat: [72.83, 21.17], calicut: [75.78, 11.25], male: [73.51, 4.18], kolkata: [88.36, 22.57], malacca: [102.25, 2.19] };
const pos = Object.fromEntries(Object.entries(ports).map(([k, v]) => [k, proj(v).map((x) => Math.round(x * 10) / 10)]));
const eq = proj([30, 0])[1];
writeFileSync("src/sim/coast.ts", `// Generated by tools/coast.mjs from Natural Earth (public domain). Do not edit.
export const CHART = { width: ${W}, height: ${H}, equatorY: ${Math.round(eq * 10) / 10} } as const;
export const LAND = ${JSON.stringify(d)};
export const GRATICULE = ${JSON.stringify(grat)};
export const PORT_XY: Record<string, [number, number]> = ${JSON.stringify(pos)};
`);
console.log("land path", d.length, "chars; ports", JSON.stringify(pos));
